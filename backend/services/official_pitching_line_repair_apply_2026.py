    partition = plan.get('identity_resolution_partition') or {}
    amendment_line = plan.get('defect_baseline_amendment_line_validation') or {}
    approved_amendment = contract['amendment_action']
    inputs = plan.get('inputs') or {}

    _check(results, 'planner_capability_is_the_reviewed_planner',
           passed=plan.get('capability') == contract['planner_capability'],
           expected=contract['planner_capability'], observed=plan.get('capability'))
    _check(results, 'planner_result_is_pass',
           passed=plan.get('result') == planner.RESULT_PASS,
           expected=planner.RESULT_PASS, observed=plan.get('result'))
    _check(results, 'planner_exit_code_is_zero',
           passed=plan.get('exit_code') == 0, expected=0, observed=plan.get('exit_code'))
    _check(results, 'planner_mode_is_read_only',
           passed=plan.get('mode') == planner.MODE_READ_ONLY,
           expected=planner.MODE_READ_ONLY, observed=plan.get('mode'))
    _check(results, 'planner_performed_no_database_writes',
           passed=plan.get('database_writes_performed') is False,
           expected=False, observed=plan.get('database_writes_performed'))
    _check(results, 'plan_scope_is_full_season',
           passed=plan.get('plan_scope') == contract['plan_scope'],
           expected=contract['plan_scope'], observed=plan.get('plan_scope'))
    _check(results, 'plan_status_is_ready_for_apply_review',
           passed=plan.get('plan_status') == contract['plan_status'],
           expected=contract['plan_status'], observed=plan.get('plan_status'))
