"""Official pitching-line repair APPLY path (2026) — one-time, fingerprint-locked.

The merged read-only planner produced a reviewed 675-action repair manifest and a single
SHA-256 manifest fingerprint. That exact fingerprint — and only that fingerprint — is
approved for execution. This module executes it once, atomically, or it writes nothing.

What "fingerprint-locked" means here. The approval is not a pattern, a prefix, an action-count
range, or a family of semantically similar plans. Immediately before opening the mutation
transaction the planner is regenerated from live production state, and the regenerated
manifest fingerprint must equal the approved constant byte for byte. A one-character
difference is a different manifest describing different writes, and it aborts before the
first write. There is no operator override for a mismatch, because an override would convert
an exact approval into a discretionary one.

Why regeneration rather than replaying a stored manifest: a stored manifest is a claim about
a database that has since moved on. Regenerating proves the same 675 actions are still the
right 675 actions against the rows that exist right now, and the fingerprint proves the
regenerated plan is the reviewed plan rather than a fresh plan that happens to look similar.

Transaction shape. One transaction covers every mutation. A dedicated PostgreSQL
transaction-level advisory lock is taken before any mutation precondition is read, so a
second invocation — or any future repair using the same lock contract — cannot interleave.
Identities are created, then insertions, then updates, then everything is read back and
verified, then the durable execution ledger row is written, then a single commit. There is no
intermediate commit and no partial success: any failure rolls back all 675 actions.

Boundaries. No delete of any kind exists in this module. No duplicate consolidation, no
phantom-row deletion, no current-team or roster mutation, no appearance-team rewrite on an
existing row, no public-surface publication, no Team State or Share Card generation. A
historical appearance never establishes present-day state. Foundation 3B stays blocked after
a successful apply and is opened only by separately reviewed post-apply validation.
"""

